// Minimal service worker — its main job here is simply to exist and register,
// which (together with the manifest) is what makes Chrome/Edge eligible to
// show the "Install app" / "Download app" prompt.
const CACHE_NAME = 'physio-accounting-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// Basic network-first fetch handler (falls back to cache if offline).
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const clone = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
